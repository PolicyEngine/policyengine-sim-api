"""Run only the small first-checkpoint benchmark, in Modal's testing environment.

No source download, deployment, production cache writes, or credential lookup.
Pass an explicitly synthetic input generated by policyengine.py's test helper.
The application ends after the run; its uniquely named volume is retained until
the evidence has been downloaded and verified. Every named Modal resource uses
the same six-character random suffix.
"""

from __future__ import annotations

import argparse
import re
import secrets
import string
import subprocess
from pathlib import Path

import modal
from policyengine.provenance.dataset_materialization import MaterializedDataset
from policyengine.tax_benefit_models.us.state_preparation import USPartitionManifest
from policyengine.utils.hashing import sha256_file
from pydantic import JsonValue, TypeAdapter

from policyengine_simulation_executor.precompute_benchmark.parallel import (
    ModalStateYearWorker,
    StateYearTask,
    USStateYearPlan,
    prepare_state_years_parallel,
)
from policyengine_simulation_executor.precompute_benchmark.modal_helpers import (
    build_benchmark_image,
    download_evidence,
)
from policyengine_simulation_executor.precompute_benchmark.profiling import Measurement


def run(
    analysis_repo: Path, fixture_source: Path, output_dir: Path, suffix: str
) -> None:
    if not re.fullmatch("[a-z0-9]{6}", suffix):
        raise ValueError("Modal names require one six-character lowercase suffix")
    if fixture_source.stat().st_size > 10 * 1024 * 1024:
        raise ValueError("The first checkpoint accepts only a small synthetic source")
    output_dir.mkdir(parents=True, exist_ok=False)
    project = Path(__file__).resolve().parents[1]
    code_revision = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=project, text=True
    ).strip()
    source = MaterializedDataset(
        data_package_name="synthetic-fixture",
        repo_type="dataset",
        revision="fixture",
        source_uri="fixture://us-inputs",
        sha256=sha256_file(fixture_source),
        path=Path("/benchmark/synthetic-source.h5"),
    )
    image = build_benchmark_image(analysis_repo, project)
    app = modal.App(f"policyengine-state-preparation-{suffix}")
    volume_name = f"policyengine-state-preparation-data-{suffix}"
    # Explicit create rejects accidental reuse of evidence or resource names.
    modal.Volume.objects.create(volume_name, environment_name="testing")
    volume = modal.Volume.from_name(volume_name, environment_name="testing")
    (output_dir / "resources.json").write_text(
        TypeAdapter(dict[str, JsonValue])
        .dump_json(
            {
                "environment": "testing",
                "app_name": app.name,
                "volume_name": volume_name,
                "suffix": suffix,
            }
        )
        .decode()
    )
    with volume.batch_upload() as upload:
        upload.put_file(fixture_source, "/synthetic-source.h5")

    @app.function(
        name=f"allocation_probe_{suffix}",
        serialized=True,
        image=image,
        cpu=1,
        memory=(2048, 2048),
        volumes={"/benchmark": volume},
        timeout=120,
        retries=0,
        single_use_containers=True,
        scaledown_window=2,
    )
    def allocation_probe(fail: bool) -> str:
        from policyengine_simulation_executor.precompute_benchmark.workers import (
            probe_impl,
        )

        try:
            return probe_impl(code_revision, source.sha256, fail=fail).model_dump_json()
        finally:
            volume.commit()

    @app.function(
        name=f"partition_source_{suffix}",
        serialized=True,
        image=image,
        cpu=2,
        memory=(4096, 4096),
        volumes={"/benchmark": volume},
        timeout=180,
        retries=0,
        single_use_containers=True,
        scaledown_window=2,
    )
    def partition_source() -> str:
        from policyengine_simulation_executor.precompute_benchmark.workers import (
            partition_impl,
        )

        try:
            manifest, _ = partition_impl(source, code_revision)
            return manifest.model_dump_json()
        finally:
            volume.commit()

    @app.function(
        name=f"prepare_state_year_{suffix}",
        serialized=True,
        image=image,
        cpu=2,
        memory=(4096, 4096),
        volumes={"/benchmark": volume},
        max_containers=2,
        timeout=180,
        retries=0,
        single_use_containers=True,
        scaledown_window=2,
    )
    def prepare_state_year(payload: str) -> str:
        from policyengine_simulation_executor.precompute_benchmark.workers import (
            prepare_impl,
        )
        from policyengine_simulation_executor.precompute_benchmark.testing import (
            synchronize_testing_workers,
        )

        # Each worker sees committed partitions; workers write distinct files.
        volume.reload()
        task = StateYearTask.model_validate_json(payload)

        def publish_ready() -> None:
            Path(
                f"/benchmark/ready-{task.partition.state_code.lower()}-{suffix}"
            ).touch()
            volume.commit()

        def both_ready() -> bool:
            names = {
                Path(entry.path).name for entry in volume.iterdir("/", recursive=False)
            }
            return {f"ready-ca-{suffix}", f"ready-ut-{suffix}"}.issubset(names)

        def synchronize() -> None:
            synchronize_testing_workers(publish_ready, both_ready, timeout_seconds=120)

        try:
            return prepare_impl(
                task,
                code_revision,
                hold_seconds=5,
                synchronize=synchronize,
            ).model_dump_json()
        finally:
            volume.commit()

    try:
        with modal.enable_output(), app.run(environment_name="testing"):
            good = Measurement.model_validate_json(allocation_probe.remote(False))
            failure = Measurement.model_validate_json(allocation_probe.remote(True))
            manifest = USPartitionManifest.model_validate_json(
                partition_source.remote()
            )
            tasks = tuple(
                StateYearTask(partition=part, year=2025)
                for part in manifest.partitions
                if part.state_code in {"CA", "UT"}
            )
            result = prepare_state_years_parallel(
                USStateYearPlan(tasks=tasks),
                ModalStateYearWorker(prepare_state_year),
                max_workers=2,
            )
            intervals = [
                (
                    task.measurement.started_unix_seconds,
                    task.measurement.started_unix_seconds
                    + task.measurement.elapsed_seconds,
                )
                for task in result.tasks
            ]
            overlap = min(end for _, end in intervals) - max(
                start for start, _ in intervals
            )
            (output_dir / "prepared-results.json").write_text(
                result.model_dump_json(indent=2)
            )
            (output_dir / "partition-manifest.json").write_text(
                manifest.model_dump_json(indent=2)
            )
            if overlap <= 0:
                raise RuntimeError(
                    "The two real Modal worker intervals did not overlap"
                )
            summary: dict[str, JsonValue] = {
                "allocation_probe": good.model_dump(mode="json"),
                "failure_probe": failure.model_dump(mode="json"),
                "worker_overlap_seconds": overlap,
                "container_memory_available": all(
                    item.measurement.container_memory_source is not None
                    for item in result.tasks
                )
                and good.container_memory_source is not None,
            }
            (output_dir / "dry-run-summary.json").write_text(
                TypeAdapter(dict[str, JsonValue]).dump_json(summary, indent=2).decode()
            )
    finally:
        download_evidence(volume, output_dir)
    print(f"Dry run completed. Evidence: {output_dir}; volume: {volume_name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis-repo", required=True, type=Path)
    parser.add_argument("--synthetic-source", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument(
        "--suffix",
        default="".join(
            secrets.choice(string.ascii_lowercase + string.digits) for _ in range(6)
        ),
    )
    args = parser.parse_args()
    run(args.analysis_repo, args.synthetic_source, args.output_dir, args.suffix)
